package dev.piko.shared.search

internal expect fun nfkcNormalize(text: String): String

/**
 * 中日韩（CJK）统一归一化与模糊匹配。
 *
 * 1. 先经平台 NFKC 将兼容表意文字（\uF900–\uFAFF）、康熙部首、全角字母数字与半角片假名折叠到标准码位；
 *    和制汉字（如 込、辻、畑、峠、枠、匂、雫、凪、榊、働）在 Unicode 中日韩统一表意文字中本就是同一码位，直接保留。
 * 2. 将片假名统一折叠为平假名，处理日文叠字符「々 / ゝ / ゞ / ヽ / ヾ」（展开为前一个字符）。
 * 3. 将分属不同码位的繁体字与日本新字体/异体字（如 櫻/桜→樱、澤/沢→泽、濱/浜→滨、發/発/髮/髪→发）统一归并到同一规范简体码位。
 */
fun normalizeCjk(text: String): String {
    if (text.isEmpty()) return ""
    val nfkc = nfkcNormalize(text)
    var changed = nfkc !== text
    val out = CharArray(nfkc.length)
    var prev = '\u0000'
    for (i in 0 until nfkc.length) {
        val raw = nfkc[i]
        val folded = when (raw) {
            in 'A'..'Z' -> (raw.code + 32).toChar()
            in '\u30A1'..'\u30F6' -> (raw.code - 0x60).toChar()
            '\u3005', '\u309D', '\u309E', '\u30FD', '\u30FE' -> if (prev != '\u0000') prev else raw
            else -> if (raw.code < HAN_VARIANT_MAP.size) HAN_VARIANT_MAP[raw.code] else raw
        }
        if (folded != raw) changed = true
        out[i] = folded
        prev = folded
    }
    return if (changed) out.concatToString() else nfkc
}

/**
 * 判断候选名称 [text] 是否匹配搜索词 [query]（支持多词空格分词、连字符忽略、简繁/日新字体互通及 CJK 有界子序列模糊匹配）。
 */
fun cjkMatches(text: String, query: String): Boolean = cjkFuzzyScore(query, text) != null

/**
 * 计算 [query] 对 [text] 的 CJK 模糊匹配得分，不匹配返回 null。
 *
 * - 支持空格切分多个关键词，所有词都命中才算匹配；
 * - 整段连续子串命中得分最高；
 * - 忽略连字符/下划线/括号/中点等分隔符后的连续子串次之（如 `ssis123` 命中 `SSIS-123`）；
 * - 对纯 CJK 词（长度 >= 2），允许有界跳跃子序列匹配（如 `进击巨人` 命中 `進擊的巨人`），避免拉丁字母与数字跨词误匹配。
 */
fun cjkFuzzyScore(query: String, text: String): Int? {
    if (query.isBlank()) return 0
    val normQuery = normalizeCjk(query).trim()
    if (normQuery.isEmpty()) return 0
    val normText = normalizeCjk(text)
    if (normText.isEmpty()) return null

    val tokens = splitTokens(normQuery)
    if (tokens.isEmpty()) return 0

    var totalScore = 0
    var compactText: String? = null
    for (token in tokens) {
        val directIdx = normText.indexOf(token)
        if (directIdx >= 0) {
            val wordStart = directIdx == 0 || !normText[directIdx - 1].isLetterOrDigit()
            totalScore += 1_000 + (if (directIdx == 0) 200 else 0) + (if (wordStart) 30 else 0) - directIdx
            continue
        }
        val compactTok = stripSeparators(token)
        if (compactTok.isEmpty()) continue
        val targetCompact = compactText ?: stripSeparators(normText).also { compactText = it }
        val compactIdx = targetCompact.indexOf(compactTok)
        if (compactIdx >= 0) {
            totalScore += 700 + (if (compactIdx == 0) 100 else 0) - compactIdx
            continue
        }
        val subseqScore = cjkSubsequenceScore(compactTok, normText) ?: return null
        totalScore += subseqScore
    }
    return totalScore - normText.length / 4
}

private fun splitTokens(text: String): List<String> {
    val result = ArrayList<String>(4)
    var start = -1
    for (i in 0 until text.length) {
        if (text[i].isWhitespace()) {
            if (start >= 0) {
                result.add(text.substring(start, i))
                start = -1
            }
        } else if (start < 0) {
            start = i
        }
    }
    if (start >= 0) result.add(text.substring(start))
    return result
}

private fun stripSeparators(text: String): String {
    var hasSep = false
    for (i in 0 until text.length) {
        if (isSeparatorChar(text[i])) {
            hasSep = true
            break
        }
    }
    if (!hasSep) return text
    val sb = StringBuilder(text.length)
    for (i in 0 until text.length) {
        val c = text[i]
        if (!isSeparatorChar(c)) sb.append(c)
    }
    return sb.toString()
}

private fun isSeparatorChar(c: Char): Boolean =
    c.isWhitespace() || c == '-' || c == '_' || c == '.' || c == '/' || c == '\\' ||
        c == '·' || c == '・' || c == '[' || c == ']' || c == '(' || c == ')' ||
        c == '【' || c == '】' || c == '（' || c == '）' || c == '「' || c == '」' ||
        c == '『' || c == '』' || c == ':' || c == '：' || c == '~' || c == '～'

private fun isCjkChar(c: Char): Boolean =
    c.code in 0x3040..0x30FF || c.code in 0x3400..0x9FFF || c.code in 0xF900..0xFAFF ||
        c.code in 0xAC00..0xD7A3 || c.code in 0x1100..0x11FF || c.code in 0x3130..0x318F ||
        c.code in 0xA960..0xA97F || c.code in 0xD7B0..0xD7FF

/**
 * 纯 CJK 词的有界子序列匹配：相邻命中字符在目标串中的间距不超过 [MAX_CJK_SUBSEQ_GAP]，
 * 既支持「进击巨人」匹配「進擊的巨人」，又防止不相关的单字跨越整条长文件名误命中。
 */
private fun cjkSubsequenceScore(token: String, normText: String): Int? {
    if (token.length < 2) return null
    for (i in 0 until token.length) {
        if (!isCjkChar(token[i])) return null
    }
    val firstChar = token[0]
    var searchStart = 0
    while (true) {
        val firstIdx = normText.indexOf(firstChar, searchStart)
        if (firstIdx < 0) return null
        var prevIdx = firstIdx
        var score = 300 - firstIdx
        var matchedAll = true
        for (i in 1 until token.length) {
            val nextIdx = normText.indexOf(token[i], prevIdx + 1)
            if (nextIdx < 0 || nextIdx - prevIdx - 1 > MAX_CJK_SUBSEQ_GAP) {
                matchedAll = false
                break
            }
            score += if (nextIdx == prevIdx + 1) 40 else (15 - (nextIdx - prevIdx - 1) * 3)
            prevIdx = nextIdx
        }
        if (matchedAll) return score
        searchStart = firstIdx + 1
    }
}

